import 'server-only';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { utils, write } from 'xlsx';
import { arr, obj, str, type RecordData, type Session } from './api';
import { posMoney, posTimeZone, posDay, type PosRegisterRow } from './pos';
import { loadPosRegisterPage, readPosRegisterReport, type PosRegisterFilters } from './production-pos';

const columns = ['Date', 'Sale Id', 'Total Qty', 'Items SKU', 'Total Paid', 'Total Profit', 'Total Discount', 'Total Amount', 'Sell Due',
  'Payment Status', 'Payment Method', 'Added By', 'Sell Note', 'Payment Note'];
const formatDate = (date: Date) => new Intl.DateTimeFormat('en-GB', { timeZone: posTimeZone }).format(date);
const rounding = (value: unknown) => Math.round(Number(value || 0));
const taka = (value: unknown) => posMoney(rounding(value)) + ' Tk';

function rowsForExport(rows: PosRegisterRow[], canSeeProfit: boolean) {
  return rows.map(({ serial, cells, amounts, subtotal }) => [
    cells.date || '-', serial ? '#' + serial : '-', Number(cells.quantity) || 0,
    [...new Set((cells.sku || '').split('\n').filter(Boolean))].join(', ') || '-',
    rounding(amounts.paid), canSeeProfit ? rounding(amounts.profit) : '-',
    rounding(amounts.discount), rounding(subtotal), rounding(amounts.due), cells.status || '-',
    cells.method || '-', cells.creator || '-', cells.note || '-', cells.paymentNote || '-',
  ]);
}

function stockDetails(data: RecordData, canSeeCost: boolean) {
  const categories = arr(data.categories).map(obj).map(category =>
    (str(category.category_name) || '-') + ': ' + rounding(category.total_available_quantity) + ' Pair/pcs');
  return [
    ...(categories.length ? categories : ['-']),
    'Total Stock Value by Purchase: ' + (canSeeCost ? taka(data.current_stock_value_by_purchase_rate) : '-'),
    'Total Stock Value by Sell: ' + taka(data.potential_sale_value_by_sale_price),
  ];
}

function headerData(auth: Session, filters: PosRegisterFilters) {
  const location = filters.locations.find(row => row.value === filters.location)?.label || (filters.location ? 'Assigned location' : 'All Locations');
  const dateRange = filters.from && filters.to ? formatDate(new Date(filters.from)) + ' - ' + formatDate(new Date(filters.to)) : '';
  const now = new Date();
  const time = new Intl.DateTimeFormat('en-US', { timeZone: posTimeZone, hour: '2-digit', minute: '2-digit' }).format(now);
  return { location, dateRange, generated: 'Generated by ' + auth.staff.name + ' at ' + formatDate(now) + ' ' + time };
}

export async function posRegisterExport(action: 'xlsx' | 'pdf', filters: PosRegisterFilters, auth: Session) {
  const pageSize = 250;
  const [{ rows, total }, report] = await Promise.all([
    loadPosRegisterPage(auth, filters, 1, pageSize), readPosRegisterReport(auth, filters),
  ]);
  if (!rows.length) return new Response('No sales to export.', { status: 404 });
  for (let page = 2; page <= Math.ceil(total / pageSize); page++) {
    rows.push(...(await loadPosRegisterPage(auth, filters, page, pageSize)).rows);
  }
  const header = headerData(auth, filters);
  const records = rowsForExport(rows, filters.canSeeProfit);
  const opening = stockDetails(obj(report.openingStock), filters.canSeeCost);
  const closing = stockDetails(obj(report.closingStock), filters.canSeeCost);
  const aggregate = (key: keyof typeof rows[number]['amounts']) => rows.reduce((sum, row) => sum + (row.amounts[key] || 0), 0);
  const soldCategories = arr(report.soldByCategory ?? obj(report.closingStock).categories).map(obj)
    .filter(row => rounding(row.total_sold ?? row.sold) > 0)
    .map(row => (str(row.category_name) || str(row.name)) + ' ' + rounding(row.total_sold ?? row.sold));
  const summaries = [
    'Total Items Sold: ' + (soldCategories.length ? soldCategories.join(', ') : rows.reduce((sum, row) => sum + Number(row.cells.quantity || 0), 0)),
    'Total Sell Value: ' + taka(report.totalSales || aggregate('total')),
    'Total Purchase Value: ' + (filters.canSeeCost ? taka(report.totalCost ?? aggregate('cost')) : '-'),
    'Total Profit: ' + (filters.canSeeProfit ? taka(report.totalProfit ?? aggregate('profit')) : '-'),
  ];
  let bytes: ArrayBuffer;
  if (action === 'xlsx') {
    const blank = Array<string>(7).fill('');
    const data = [['Griipbuddy'], ['Sales Report'], [header.location], [header.dateRange], [header.generated], [], columns,
      ...records.map(([date, ...rest]) => [String(date).replace('\n', ' '), ...rest]),
      [], [summaries[0], ...Array<string>(10).fill(''), ...summaries.slice(1)], [],
      ['Opening Stock', ...blank, 'Closing Stock'],
      ...Array.from({ length: Math.max(opening.length, closing.length) }, (_, i) => [opening[i] || '', ...blank, closing[i] || '']),
    ];
    const sheet = utils.aoa_to_sheet(data);
    sheet['!merges'] = [0, 1, 2, 3, 4].map(r => ({ s: { r, c: 0 }, e: { r, c: columns.length - 1 } }));
    sheet['!cols'] = [38, 22, 20, 32, 24, 14, 14, 14, 12, 14, 14, 16, 58, 58].map(wch => ({ wch }));
    for (let r = 7; r < 7 + records.length; r++) {
      for (const c of [4, 5, 6, 7, 8]) {
        const cell = sheet[utils.encode_cell({ r, c })];
        if (cell?.t === 'n') cell.z = '#,##0" Tk"';
      }
    }
    const book = utils.book_new();
    utils.book_append_sheet(book, sheet, 'Sales Report');
    bytes = write(book, { type: 'array', bookType: 'xlsx' }) as ArrayBuffer;
  } else {
    const pdf: jsPDF & { lastAutoTable?: { finalY: number } } = new jsPDF({ orientation: 'landscape', format: 'a4' });
    const center = pdf.internal.pageSize.getWidth() / 2;
    pdf.setFontSize(16); pdf.text('Griipbuddy', center, 15, { align: 'center' });
    pdf.setFontSize(13); pdf.text('Sales Report', center, 22, { align: 'center' });
    pdf.text(header.location, center, 29, { align: 'center' });
    if (header.dateRange) pdf.text(header.dateRange, center, 35, { align: 'center' });
    pdf.setFontSize(10); pdf.text(header.generated, 12, 38);
    autoTable(pdf, {
      startY: 42, margin: { left: 12, right: 12 }, head: [columns],
      body: records.map(row => row.map((value, index) => index >= 4 && index <= 8 && typeof value === 'number' ? taka(value) : value)),
      styles: { fontSize: 8, cellPadding: 2, overflow: 'linebreak' }, headStyles: { fillColor: [10, 51, 67] }, theme: 'grid',
    });
    let y = (pdf.lastAutoTable?.finalY || 42) + 12;
    if (y + 50 > pdf.internal.pageSize.getHeight() - 12) { pdf.addPage(); y = 16; }
    pdf.text(summaries[0], 12, y);
    pdf.text(summaries[1], center, y, { align: 'center' });
    pdf.text(summaries[3], pdf.internal.pageSize.getWidth() - 12, y, { align: 'right' });
    autoTable(pdf, {
      startY: y + 6, margin: { left: 12, right: 12 }, head: [['Opening Stock', 'Closing Stock']],
      body: Array.from({ length: Math.max(opening.length, closing.length) }, (_, i) => [opening[i] || '', closing[i] || '']),
      styles: { fontSize: 10, cellPadding: 2 }, theme: 'plain',
    });
    bytes = pdf.output('arraybuffer');
  }
  const filename = 'sales_report_' + header.location.replace(/[^a-z0-9]+/gi, '_') + '_' + posDay() + '.' + action;
  return new Response(bytes, { headers: {
    'Cache-Control': 'private, no-store', 'X-Content-Type-Options': 'nosniff',
    'Content-Type': action === 'pdf' ? 'application/pdf' : 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    'Content-Disposition': 'attachment; filename="' + filename + '"',
  } });
}
